"""Генерує src/RoundsBots/Logic/CardKnowledge.g.cs з docs/cards.json (запуск: python tools/gen_card_knowledge.py)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cards = json.loads((root / "docs" / "cards.json").read_text(encoding="utf-8"))
BASE_RELOAD = 2.0     # базова перезарядка, с (додатки в секундах -> множник)
BASE_BLOCK_CD = 4.0   # базовий кулдаун блоку, с
risk = {"none": 0, "low": 1, "medium": 2, "high": 3}
lines = []
for c in sorted(cards, key=lambda c: c["name"].upper()):
    if not c.get("inPool", True):
        continue
    name = c["name"].upper().replace("\\", "\\\\").replace('"', '\\"')
    e = c.get("effects", {})
    def f(v):
        return f"{float(v):.4f}f"
    reload_mult = e.get("reloadTimeMult", 1.0) * (1.0 + e.get("reloadTimeAddSec", 0.0) / BASE_RELOAD)
    block_mult = e.get("blockCooldownMult", 1.0) * (1.0 + e.get("blockCooldownAddSec", 0.0) / BASE_BLOCK_CD)
    rarity = {"common": 0, "uncommon": 1, "rare": 2}.get(str(c.get("rarity", "")).lower(), 0)
    features = (
        f"new CardFeatures {{ Rarity = {rarity}, DamageMultiplier = {f(e.get('damageMult', 1))}, "
        f"AttackSpeedMultiplier = {f(e.get('attackCooldownMult', 1))}, ReloadTimeMultiplier = {f(reload_mult)}, "
        f"AmmoAdd = {int(e.get('ammoAdd', 0))}, ProjectilesAdd = {int(e.get('projectilesAdd', 0))}, "
        f"HealthMultiplier = {f(e.get('healthMult', 1))}, MoveSpeedMultiplier = {f(e.get('moveSpeedMult', 1))}, "
        f"LifeSteal = {f(e.get('lifeStealAdd', 0))}, Regen = {f(e.get('regenPerSec', 0))}, "
        f"BlockCooldownMultiplier = {f(block_mult)}, ExtraBlocks = {int(e.get('extraBlocks', 0))}, "
        f"Reflects = {int(e.get('bouncesAdd', 0))}, PlayerSizeMultiplier = {f(e.get('playerSizeMult', 1))}, "
        f"ExtraJumps = {int(e.get('extraJumps', 0))}, Respawns = {int(e.get('respawnsAdd', 0))}, "
        f"SpecialValue = {f(c.get('specialValue', 0))} }}"
    )
    self_damage = any("selfdamage" in k.lower() and v for k, v in e.items())
    lines.append(f'            ["{name}"] = new CardTraits({risk.get(c.get("botRisk", "none"), 0)}, {str(bool(c.get("closeRange"))).lower()}, {features}, {str(self_damage).lower()}),')
out = f'''// <auto-generated> tools/gen_card_knowledge.py з docs/cards.json — не редагувати вручну. </auto-generated>
using System.Collections.Generic;

namespace RoundsBots.Logic
{{
    public static partial class CardKnowledge
    {{
        private static readonly Dictionary<string, CardTraits> Table = new Dictionary<string, CardTraits>
        {{
{chr(10).join(lines)}
        }};
    }}
}}
'''
(root / "src" / "RoundsBots" / "Logic" / "CardKnowledge.g.cs").write_text(out, encoding="utf-8")
print(len(lines), "cards")
